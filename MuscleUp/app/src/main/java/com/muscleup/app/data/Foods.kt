package com.muscleup.app.data

import org.json.JSONObject

/** 每 100g（或 100ml）的营养数据；portion 为常用份量 */
data class Food(
    val name: String, val category: String, val kcal: Double, val protein: Double, val carbs: Double, val fat: Double,
    val portionName: String = "100克", val portionG: Double = 100.0,
) {
    fun toJson() = JSONObject().put("n", name).put("cat", category).put("k", kcal).put("p", protein)
        .put("c", carbs).put("f", fat).put("pn", portionName).put("pg", portionG)

    companion object {
        fun from(o: JSONObject) = Food(
            o.getString("n"), o.optString("cat", "自定义"), o.optDouble("k"), o.optDouble("p"), o.optDouble("c"),
            o.optDouble("f"), o.optString("pn", "100克"), o.optDouble("pg", 100.0),
        )
    }
}

